#!/usr/bin/env python3
"""Snapshot the EXFOR dictionaries the TRANS checker needs into services/nsr-api/exfor_check_dicts.py (brief 71).

Source: the full archive dictionary in JSON that N. Otuka's forexy codes ship (git.oecd-nea.org/exfor/tools/forexy,
tests/files/dict_<N>.json, made by x4_dica2j from the NRDC dictionary transmission). It carries every field the checker
uses: the nuclides of dictionary 227, each keyword's code dictionary and required flag (002), the unit families of
headings, units and quantities (024, 025, 236), the particle subfield flags (033) and the general-modifier flags (034).
The lake's nsr.exfor_dict_* tables come from the IAEA's latest.json, which drops those fields, so they are not used.

  python3 scripts/exfor-check/dicts.py [9134]      # runs on the dev box; writes the module beside the route
"""
import json, os, sys, urllib.request

N = sys.argv[1] if len(sys.argv) > 1 else "9134"
URL = ("https://git.oecd-nea.org/api/v4/projects/exfor%2Ftools%2Fforexy/repository/files/"
       f"tests%2Ffiles%2Fdict_{N}.json/raw?ref=main")
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "services", "nsr-api", "exfor_check_dicts.py")


def fetch():
    local = os.environ.get("DICT_JSON")
    if local:
        return json.load(open(local))
    req = urllib.request.Request(URL, headers={"User-Agent": "NSRgpt-crawler/1.0"})
    return json.load(urllib.request.urlopen(req, timeout=120))


def main():
    d = fetch()
    key = lambda r: (r.get("code") if "code" in r else r.get("keyword")) or ""
    rows = lambda n: [r for r in d.get(n, []) if key(r)]
    st = lambda r: (r.get("status_code") or "").strip()
    out = {"version": str(d.get("transmission_id")), "stamp": d.get("time_stamp"), "source": URL.split("/raw")[0], "d": {}}
    D = out["d"]
    # code -> status, for the dictionaries the checker only looks codes up in
    for n in ("001", "003", "004", "005", "006", "007", "015", "017", "018", "019", "020", "021", "022", "023", "030",
              "031", "032", "035", "037", "038", "207", "209", "227"):
        D[n] = {key(r): st(r) for r in rows(n)}
    D["002"] = {key(r): [r.get("code_required") or "", r.get("pointer_to_related_dictionary"),
                         r.get("keyword_required") or "", st(r)] for r in rows("002")}
    D["008"] = {str(r["atomic_number_of_element"]): [r["element_symbol"], st(r)] for r in d["008"]}
    D["016"] = {key(r): [r.get("subentry_number_field_flag") or "", st(r)] for r in rows("016")}
    D["024"] = {key(r): [r.get("data_type_flag_1"), r.get("data_type_flag_2"), (r.get("family_flag") or "").strip(),
                         (r.get("unit_family_code") or "").strip(), st(r)] for r in rows("024")}
    D["025"] = {key(r): [(r.get("unit_family_code") or "").strip(), st(r)] for r in rows("025")}
    D["033"] = {key(r): ["".join((r.get(f"allowed_subfield_flag_{i}") or "").strip() for i in range(1, 5)), st(r)]
                for r in rows("033")}
    D["034"] = {key(r): [(r.get("general_quantity_modifier_flag") or "").strip(), st(r)] for r in rows("034")}
    D["236"] = {key(r): [(r.get("reaction_type_code") or "").strip(), (r.get("unit_family_code") or "").strip(), st(r)]
                for r in rows("236")}
    text = json.dumps(out, separators=(",", ":"), sort_keys=True)
    with open(OUT, "w") as f:
        f.write("# Generated by scripts/exfor-check/dicts.py from forexy's dict_%s.json (%s); do not edit.\n"
                "import json\nDICTS = json.loads(%r)\n" % (N, out["stamp"], text))
    statuses = sorted({s for n, v in D.items() for x in v.values() for s in ([x] if isinstance(x, str) else [x[-1]])})
    print(f"dictionary {out['version']} ({out['stamp']}): {sum(len(v) for v in D.values())} codes in {len(D)} "
          f"dictionaries, {len(text)} bytes; statuses {statuses}")


if __name__ == "__main__":
    main()
